# 선수각을 유속 쪽으로 비스듬히 잡는 crabbing 기동이 필요하다.
# PID 가 어려워하고 RL 이 잘하는 지점이며, 본 연구의 난이도 근거다.
# -----------------------------------------------------------------------------
THRUSTER_MOMENT_ARM = THRUSTER_Y  # 0.295 m


def allocation_matrix() -> list[list[float]]:
    """3자유도 배분 행렬 B (3×2). tau = B @ [T_port, T_stbd]."""
    ly = THRUSTER_MOMENT_ARM
    return [
        [1.0, 1.0],  # X surge
        [0.0, 0.0],  # Y sway  ← 부족구동
        [+ly, -ly],  # N yaw
    ]


# =============================================================================
# 유체동역학 계수 (3자유도 Fossen 조종 모델)
#
# [SDF] 의 gz-waves 유체동역학 플러그인은 메시에서 압력항력을 직접 적분하는 방식이라
# Fossen 계수를 그대로 주지 않는다. 따라서 아래 값은 직접 정한다.
#
# 전진(surge) 항력만은 추정이 아니다 — [SPEC] 최대속력으로 역산한다.
#
#   정상상태에서 추력과 항력이 균형:  T_total = |X_u|·U + |X_uu|·U²
#   (선형·2차 감쇠가 **함께** 작용한다. 2차항만 쓰면 X_uu 를 과대평가한다)
#
#   |X_uu| = (T_total - |X_u|·U_max) / U_max²
#          = (70 N - 8.0 × 3.0) / 3.0²
#          = 5.111 N·s²/m²
#
# 검산: 5.111u² + 8.0u - 70 = 0  →  u = 3.0000 m/s  ✓
# 제조사 공식 최대속력을 시뮬레이터가 재현하도록 맞추는 것이므로 검증 가능한 보정이다.
# (초기에 2차항만으로 역산해 7.78 을 얻었으나 선형항 누락으로 최대속력이 2.53 m/s 로
#  15.7% 낮게 나왔다. dynamics.verify_max_speed() 가 이 오류를 잡아냈다.)
# =============================================================================


