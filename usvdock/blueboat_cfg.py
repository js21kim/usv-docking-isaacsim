#
#   [X]   [ 1      1   ] [T_port ]
#   [Y] = [ 0      0   ] [T_stbd ]
#   [N]   [+ly   -ly   ]
#
# Y 행이 전부 0 이라는 것이 이 플랫폼의 본질이다 — **부족구동(underactuated)**.
