@dataclass
class SensorMountCfg:
    """센서 장착 위치 (base_link 기준, 선체 중심 기준 x=0).

    LiDAR 는 **Livox Mid-360** (사용자 확인). 이 센서의 수직 시야가
    본 연구의 설계를 지배하므로 아래 주석에 근거를 남긴다.

    ── Mid-360 수직 시야 -7° ~ +52° 의 결과 ──────────────────────────────
    수직 시야가 **위로 편향**되어 있다. 아래는 7° 뿐이다.
    따라서 LiDAR 보다 낮은 물체는 일정 거리 밖에서만 보인다:

        최소 가시 수평거리 = (LiDAR높이 - 물체높이) / tan(7°)

    기둥 상단이 수면 위 0.50 m 일 때, LiDAR 장착 높이별 계산:

        h=0.45 m  기둥이 LiDAR 보다 위  → 상향시야(+52°), 사실상 항상 보임
        h=0.60 m  기둥이 0.10 m 아래    → 0.81 m 안쪽에서 소실
        h=0.70 m  기둥이 0.20 m 아래    → 1.63 m 안쪽에서 소실
        h=1.20 m  기둥이 0.70 m 아래    → 5.70 m 안쪽에서 소실

    즉 마스트를 높게 달면 **접근 종단에서 기둥이 시야에서 사라진다.**
    정밀도가 가장 필요한 순간에 눈이 감기는 셈이다.

    → 설계 결정: LiDAR 를 기둥 상단(0.50 m)보다 **낮게** 단다.
      본 연구는 수면 위 0.45 m 로 고정한다. 임의로 고른 값이 아니라
      위 부등식에서 나온 값이다.

    ── 수면과 수중: 시야 문제가 아니라 물리 문제 ─────────────────────────
    LiDAR 는 수면과 수중을 **거리·시야와 무관하게** 관측하지 못한다. 이유 둘:

      (1) 정반사 — 장착 0.45 m 에서 하향 7° 는 수면 법선 기준 입사각 83°,
          거의 스침각(grazing)이다. 물은 이 각도에서 강한 경면 반사체라
          빔이 반사되어 날아가고 센서로 돌아오지 않는다.
      (2) 905 nm 흡수 — 설령 입사해도 물의 근적외 흡수가 극심해
          침투 깊이가 mm~cm 수준이다. 수중 물체까지 왕복할 수 없다.

    → **모델링 결정: 수면 평면을 LiDAR 레이캐스트 대상 메시에서 제외한다.**
      수면으로 향한 광선은 무반사(no return, = max range 또는 invalid)로 처리.

      이걸 지키지 않으면 시뮬레이터가 거짓말을 한다. RayCaster 에 수면 메시를
      넣어두면 광선이 수면에 맞아 거리값을 돌려주고, 실제 Mid-360 이 결코 주지
      않는 지면 기준 신호를 정책이 공짜로 얻는다. 그 정책은 2026-08 공학수조
      실험에서 그대로 무너진다. 전형적인 sim-to-real 갭이며, 본 프로젝트가
      sim2real 을 주제로 내세우는 이상 반드시 막아야 하는 종류의 오류다.

    → 결과적으로 LiDAR 가 보는 것은 **수면 위로 돌출한 고체뿐**이다:
      기둥, 수면 위 벽면. 그 외는 전부 void.

    ── 두 센서의 사각이 상보적이다 ───────────────────────────────────────
    LiDAR : 수면 위만. 게다가 종단 접근에서 하향 7° 제약으로 기둥이 소실될 수 있다
    FLS   : 수면 아래만. 음향이므로 물이 오히려 전달 매질이다

    미션 2 의 수중 돌출 기초부는 LiDAR 에 **원리적으로** 보이지 않는다.
    센서를 하나 더 붙여서 좋아지는 것이 아니라,
    **도킹 종단이 정확히 LiDAR 의 사각에 놓인다**는 것이 본 연구의 논지다.
    """

    # 수상 LiDAR — Livox Mid-360, 선체 중심 상부
    # 높이 0.45 m: 기둥 상단 0.50 m 보다 낮게 (위 주석의 부등식 참조)
    lidar_pos: tuple[float, float, float] = (0.0, 0.0, 0.45)  # [CAL] 수면 기준 높이
    lidar_h_fov_deg: float = 360.0  # [SPEC-LIVOX]
    lidar_v_fov_min_deg: float = -7.0  # [SPEC-LIVOX] 하향 한계 — 설계를 지배하는 값
    lidar_v_fov_max_deg: float = 52.0  # [SPEC-LIVOX] 상향 한계
    lidar_range_10pct: float = 40.0  # [SPEC-LIVOX] 반사율 10% 에서 [m]
    lidar_range_80pct: float = 70.0  # [SPEC-LIVOX] 반사율 80% 에서 [m]
    lidar_min_range: float = 0.10  # [SPEC-LIVOX] 근접 사각 [m]
    lidar_point_rate: int = 200_000  # [SPEC-LIVOX] points/s (first return)
    lidar_frame_hz: float = 10.0  # [SPEC-LIVOX]
    lidar_range_sigma: float = 0.02  # [SPEC-LIVOX] 10 m 에서 1σ ≤ 2 cm

    # RL 관측용 다운샘플 — 20만 점/s 를 그대로 정책에 넣지 않는다.
    # RayCaster 로 고정 각도 격자를 쏘아 거리 벡터를 만든다.
    lidar_obs_h_bins: int = 72  # 방위 5° 간격 — **정책 입력용** 저해상도
    # 검출용 고해상도. 72빈(5°)으로는 0.2 m 핑거를 6~12 m 에서 못 본다:
    #   6 m 에서 핑거가 차지하는 각도 = 0.35/6 = 3.3°  → 5° 격자로는 0~1 개 빔
    # 실제 Mid-360 은 10 Hz 에 20,000 점(0.2 m 근접사각, 200k pts/s)이라 훨씬 조밀하다.
    # 72빈은 정책 입력을 줄이려는 다운샘플일 뿐이며, 검출은 실제에 가깝게 360빈(1°)으로 한다.
    lidar_det_h_bins: int = 360
    lidar_obs_max_range: float = 35.0  # 수조 최장변

    # 수중 FLS — 선체 중심 하부, 전방 주시
    #
    # ★ 하방 경사를 주면 안 된다. LiDAR 와 같은 종류의 함정이 여기에도 있다.
    #   pitch=-10°, vFOV=20° 로 두면 빔이 -20°~0° 를 덮는다. 즉 **FLS 자신보다
    #   얕은 것을 못 본다.** 그런데 기초부 상단 수심은 0.15~0.35 m 이고 FLS 는
    #   0.25 m 에 있으므로, 얕은 기초부(0.15 m)가 FLS 보다 위에 놓여 안 보인다.
    #   미션2 의 위험 조건이 바로 "얕은 기초부" 이므로 정확히 봐야 할 것을 놓친다.
    #
    #   → pitch = 0 (수평), vFOV 20° → 빔이 -10°~+10°.
    #     거리 d 에서 수심 0.25 ± d·tan(10°) 를 덮는다.
    #     수심 0.15 m 기초부는 d ≥ 0.10/tan(10°) = 0.57 m 부터 보인다.
    #     충돌 훨씬 전에 검출된다.
    #
    #   대가: 수평 빔은 수면 다중경로(surface multipath) 를 받는다. 실제 FLS 운용의
    #   알려진 문제이며, 본 시뮬레이션에서는 모델링하지 않는다(한계로 명시).
    fls_pos: tuple[float, float, float] = (0.0, 0.0, -0.25)  # 프로펠러(0.272)보다 살짝 위
    fls_pitch_deg: float = 0.0  # 수평 — 위 주석 참조
    fls_h_fov_deg: float = 130.0  # [EST] 전형적 FLS 방위 시야
    fls_v_fov_deg: float = 20.0  # [EST] 고도각 시야
    fls_n_beams: int = 128  # [EST]
    fls_max_range: float = 20.0  # [EST]


